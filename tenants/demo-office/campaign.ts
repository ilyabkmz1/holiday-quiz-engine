export const tasks = campaign.rooms.flatMap((room) => room.tasks);

export function getRoom(roomId: string) {
  return campaign.rooms.find((room) => room.id === roomId);
}

export function getTask(taskId: string) {
  return tasks.find((task) => task.id === taskId);
}

export function getRoomOfTask(taskId: string) {
  return campaign.rooms.find((room) => room.tasks.some((task) => task.id === taskId));
}

export function getRushItem(itemId: string) {
  return campaign.rush.pool.find((item) => item.id === itemId);
}
